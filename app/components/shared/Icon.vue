	/** lucide icon name, e.g. "Search", "Trash2" */
	name: { type: String, required: true },
	/** size in px; also accepts a tailwind size class via `class` */
	size: { type: [Number, String], default: null },
	/** extra classes */
	class: { type: [String, Array, Object], default: null },
	/** stroke width (lucide default is 2) */
	strokeWidth: { type: [Number, String], default: null },
	/** icon color */
	color: { type: String, default: null },
})

const resolved = computed(() => ICONS[props.name] ?? HelpCircle)

const iconClass = computed(() => {
	const classes = []
	if (props.size != null) {
		const s = typeof props.size === 'number' ? `${props.size}px` : props.size
		classes.push(`size-${props.size}`, `w-${props.size}`, `h-${props.size}`)
	}
	if (props.strokeWidth != null) classes.push(`stroke-[${typeof props.strokeWidth === 'number' ? props.strokeWidth : props.strokeWidth}]`)
	if (props.color != null) classes.push(`text-${props.color}`)
	if (props.class) classes.push(props.class)
	return classes.filter(Boolean).join(' ')
})
